"""Writes src/common/speech_voices.inc: the espeak-ng languages and voice variants the
Speech oscillator's menus list, from third_party/espeak-ng/espeak-ng-data.

Presets store a menu position, so a later espeak-ng update must append new
entries at the end of each list instead of running this script again blindly:
regenerate, then move the new lines to the end (see README.atlas.md).

    python3 src/common/speech/generate_speech_voices.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
DATA = os.path.join(ROOT, "third_party", "espeak-ng", "espeak-ng-data")
OUT = os.path.join(ROOT, "src", "common", "speech_voices.inc")


def voice_name(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            parts = line.strip().split(None, 1)
            if len(parts) == 2 and parts[0] == "name":
                return parts[1].strip()
    return None


def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    languages = []
    lang_root = os.path.join(DATA, "lang")
    for directory, _, files in os.walk(lang_root):
        for name in files:
            path = os.path.join(directory, name)
            identifier = os.path.relpath(path, lang_root).replace(os.sep, "/")
            display = voice_name(path)
            # espeak-ng's own test language.
            if display is None or display.endswith("-test"):
                continue
            languages.append((display, identifier))
    languages.sort(key=lambda entry: (entry[0].casefold(), entry[1]))

    variants = []
    variant_root = os.path.join(DATA, "voices", "!v")
    for name in os.listdir(variant_root):
        display = voice_name(os.path.join(variant_root, name))
        if display is not None:
            variants.append((display.replace("_", " "), name))
    variants.sort(key=lambda entry: (entry[0].casefold(), entry[1]))

    with open(OUT, "w", encoding="utf-8") as out:
        out.write("// Generated by generate_speech_voices.py from espeak-ng's data. Append only:\n")
        out.write("// presets store positions in these lists.\n")
        out.write("// SPEECH_LANGUAGE(display name, voice identifier under espeak-ng-data/lang)\n")
        for display, identifier in languages:
            out.write("SPEECH_LANGUAGE(%s, %s)\n" % (quote(display), quote(identifier)))
        out.write("// SPEECH_VARIANT(display name, file under espeak-ng-data/voices/!v)\n")
        for display, identifier in variants:
            out.write("SPEECH_VARIANT(%s, %s)\n" % (quote(display), quote(identifier)))
    print("%d languages, %d variants" % (len(languages), len(variants)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
